#!/usr/bin/env python3
"""Trace every output difference to the operation, the legacy lines and the Java lines that produce it.

    python3 trace_diff.py <system> [--workspace DIR]

Re-judges equivalence/cases.json and fresh-cases.json with compare.py, reads the row-by-row diagnostics run_case.py
wrote (diag/<case>/<TABLE>.txt), and joins each differing column to:

  the ETL that owns the table          RUN.json
  the operation(s) that write it       inventory/<ETL>.json, ops[].writes ("TABLE.COLUMN", or "TABLE" for all)
  the legacy lines                     the op's source_loc
  the Java lines                       the `// ETL-xxx/OP-nn` comments in modernized/<system>/java/src/main
  a cascade note                       when an ETL this one depends on (ETLS.json depends_on) also differs, fix
                                       that one first: its wrong output may be this one's wrong input

Writes analysis/<system>/equivalence/TRACE.md and prints a short summary. Exit 0 when nothing differs, 1 when
something does, 2 for unusable input. It explains; compare.py still decides.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
import etl_artifacts as ea  # noqa: E402
import loop_gate  # noqa: E402

DIFF = re.compile(r'^key (.*?): "?([^"=]+?)"? legacy=(.*) new=(.*)$')
ONLY = re.compile(r"^key (.*?): only in (legacy|new)$")


def diag_rows(path):
    """-> list of (column or '(row)', key, legacy, new) from one run_case diag file."""
    out = []
    try:
        lines = ea.read(path).splitlines()
    except OSError:
        return [("(table)", "", "", "diagnostic file missing")]
    for line in lines:
        m = DIFF.match(line)
        if m:
            out.append((m.group(2).strip().upper(), m.group(1), m.group(3), m.group(4)))
            continue
        m = ONLY.match(line)
        if m:
            out.append(("(row)", m.group(1), "present" if m.group(2) == "legacy" else "absent",
                        "present" if m.group(2) == "new" else "absent"))
            continue
        if "table missing" in line or line.startswith("columns differ"):
            out.append(("(table)", "", "", line))
    return out


def writers(inv, table, column):
    hits = []
    for op in inv.get("ops", []):
        for w in op.get("writes") or []:
            w = str(w).upper().replace('"', "")
            t, _, c = w.partition(".")
            if t == table and (c in ("", "*") or c == column or column in ("(ROW)", "(TABLE)")):
                hits.append(op)
                break
    return hits


def trace(p):
    a, eq = p["analysis"], p["eq"]
    run = ea.load_json(os.path.join(a, "RUN.json"))
    etls = {e["id"]: e for e in ea.load_json(os.path.join(a, "ETLS.json")).get("etls", [])}
    table_etl = {t["name"].upper(): t.get("etl") for t in run.get("tables", [])}
    comments = ea.op_comments(p["java"])
    found = {}   # (etl, table, column) -> {"cases": set, "samples": []}
    for name, sub in (("cases.json", ""), ("fresh-cases.json", "fresh")):
        records, _ = loop_gate.judge(os.path.join(eq, name))
        for r in records:
            if r["verdict"] not in ("differs", "missing"):
                continue
            case, _, table = r["id"].partition("-")
            table = table.upper()
            etl = table_etl.get(table, "?")
            diag = os.path.join(eq, sub, "diag", case, table + ".txt") if sub else os.path.join(eq, "diag", case, table + ".txt")
            rows = diag_rows(diag) or [("(table)", "", "", r.get("reason", ""))]
            for col, key, old, new in rows:
                slot = found.setdefault((etl, table, col), {"cases": set(), "samples": []})
                slot["cases"].add(("fresh/" if sub else "") + case)
                if len(slot["samples"]) < 3:
                    slot["samples"].append("%s key %s: legacy=%s new=%s" % (case, key, old, new))
    differing = {k[0] for k in found}
    lines = ["# Difference trace", "", "Generated by trace_diff.py. compare.py decides same or different; this "
             "file only explains where a difference comes from.", ""]
    if not found:
        lines.append("No differences.")
    summary = []
    for etl in sorted(differing):
        deps = [d for d in (etls.get(etl, {}).get("depends_on") or []) if d in differing]
        lines += ["## %s %s" % (etl, etls.get(etl, {}).get("name", "")), ""]
        if deps:
            lines += ["**Possible cascade:** %s also differ%s and %s depends on %s. Fix %s first; these differences "
                      "may disappear." % (", ".join(deps), "s" if len(deps) == 1 else "", etl,
                                          "it" if len(deps) == 1 else "them", ", ".join(deps)), ""]
        try:
            inv = ea.inventory(a, etl)
        except ea.ArtifactError:
            inv = {"ops": []}
        lines += ["| Table.column | Cases | Operation | Legacy | Java | Samples |", "|---|---|---|---|---|---|"]
        for (e, table, col), slot in sorted(found.items()):
            if e != etl:
                continue
            ops = writers(inv, table, col)
            opcell = "; ".join("%s %s" % (o.get("op_id"), str(o.get("does", ""))[:60]) for o in ops) or "**no op writes it** (missing from the inventory?)"
            legacy = "; ".join(str(o.get("source_loc", "")) for o in ops)
            java = "; ".join("%s:%d" % loc for o in ops for loc in comments.get("%s/%s" % (etl, o.get("op_id")), [])[:2])
            cases = sorted(slot["cases"])
            lines.append("| %s.%s | %d (%s) | %s | %s | %s | %s |" % (
                table, col, len(cases), ", ".join(cases[:4]), opcell.replace("|", "/"), legacy, java,
                "<br>".join(s.replace("|", "/") for s in slot["samples"])))
            summary.append("%s %s.%s in %d case(s) -> %s%s" % (etl, table, col, len(cases),
                           ", ".join("%s (%s)" % (o.get("op_id"), o.get("source_loc")) for o in ops) or "no op",
                           " [possible cascade from %s]" % ",".join(deps) if deps else ""))
        lines.append("")
    path = os.path.join(eq, "TRACE.md")
    os.makedirs(eq, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return summary, path


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("system")
    ap.add_argument("--workspace", default=".")
    a = ap.parse_args(argv)
    try:
        summary, path = trace(ea.paths(a.workspace, a.system))
    except (ea.ArtifactError, loop_gate.InputError) as err:
        print("trace_diff: %s" % err, file=sys.stderr)
        return 2
    for s in summary:
        print(s)
    print("trace: %s (%d difference group(s))" % (path, len(summary)))
    return 1 if summary else 0


if __name__ == "__main__":
    sys.exit(main())
